# Simple Arithmetic Operator Program
a = 10
b = 3

print(f"Addition: {a} + {b} =", a + b) # 13 -> Addition
print(f"Subtraction: {a} - {b} =", a - b) # 7 -> Subtraction
print(f"Multiplication: {a} * {b} =", a * b) # 30 -> Multiplication
print(f"Division: {a} / {b} =", a / b) # 3.333... -> Division
print(f"Floor Division: {a} // {b} =", a // b) # 3 -> Floor Division
print(f"Modulus: {a} % {b} =", a % b) # 1 -> Modulus
print(f"Exponentiation: {a} ** {b} =", a ** b) # 1000 -> Exponentiation
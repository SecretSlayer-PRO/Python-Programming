# Simple Assignment Operator Program
a = 10  # Assign 10
print(a)
a += 5  # a = a + 5 -> 15
print(a)
a -= 3  # a = a - 3 -> 12
print(a)
a *= 2  # a = a * 2 -> 24
print(a)
a /= 4  # a = a / 4 -> 6.0
print(a)
a //= 2  # a = a // 2 -> 3.0
print(a)
a **= 3  # a = a ** 3 -> 27.0
print(a)
a %= 5  # a = a % 5 -> 2.0
print(a)  # 2.0